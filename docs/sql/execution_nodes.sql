-- 2b. Append child nodes for every approval and publish job on a post.
--
-- Replaces the two bare INSERT statements in smm_gtm_bridge.sql 3b, which
-- were not idempotent: re-running the bridge for the same post duplicated
-- every child node. The NOT EXISTS guard makes re-ingestion safe.
CREATE OR REPLACE FUNCTION smm.append_post_child_nodes(
    p_organization_id      uuid,
    p_workflow_instance_id uuid,
    p_parent_node_id       uuid,
    p_post_id              uuid
)
RETURNS integer
LANGUAGE plpgsql AS $$
DECLARE
    v_now      timestamptz := now();
    v_inserted integer;
    v_total    integer := 0;
BEGIN
    INSERT INTO execution_nodes (
        id, organization_id, workflow_instance_id, parent_node_id,
        node_type, status, display_name, ref_id, ref_type,
        created_at, updated_at
    )
    SELECT
        gen_random_uuid(), p_organization_id, p_workflow_instance_id, p_parent_node_id,
        'APPROVAL', 'PENDING', 'approval:' || a.stage, a.id, 'APPROVAL',
        v_now, v_now
    FROM approvals a
    WHERE a.post_id = p_post_id
      AND a.organization_id = p_organization_id
      AND NOT EXISTS (
          SELECT 1 FROM execution_nodes n
          WHERE n.organization_id      = p_organization_id
            AND n.workflow_instance_id = p_workflow_instance_id
            AND n.ref_type             = 'APPROVAL'
            AND n.ref_id               = a.id
      );
    GET DIAGNOSTICS v_inserted = ROW_COUNT;
    v_total := v_total + v_inserted;

    INSERT INTO execution_nodes (
        id, organization_id, workflow_instance_id, parent_node_id,
        node_type, status, display_name, ref_id, ref_type,
        created_at, updated_at
    )
    SELECT
        gen_random_uuid(), p_organization_id, p_workflow_instance_id, p_parent_node_id,
        'PUBLISH_JOB', 'PENDING', 'publish:' || j.id::text, j.id, 'PUBLISH_JOB',
        v_now, v_now
    FROM publish_jobs j
    WHERE j.post_id = p_post_id
      AND j.organization_id = p_organization_id
      AND NOT EXISTS (
          SELECT 1 FROM execution_nodes n
          WHERE n.organization_id      = p_organization_id
            AND n.workflow_instance_id = p_workflow_instance_id
            AND n.ref_type             = 'PUBLISH_JOB'
            AND n.ref_id               = j.id
      );
    GET DIAGNOSTICS v_inserted = ROW_COUNT;
    v_total := v_total + v_inserted;

    RETURN v_total;
END;
$$;


-- 2c. Complete or fail a node by its (workflow, ref) coordinates.
--
-- smm_gtm_bridge.sql 3c did this as two loose UPDATEs with no
-- organization_id predicate — a cross-tenant write if two orgs ever collide
-- on a ref_id. Tenant scoping is mandatory here per the repository-layer
-- defense-in-depth rule.
CREATE OR REPLACE FUNCTION smm.complete_execution_node(
    p_organization_id      uuid,
    p_workflow_instance_id uuid,
    p_ref_id               uuid,
    p_ref_type             execution_node_ref_type,
    p_status               workflow_node_status,
    p_failure_reason       varchar(1000) DEFAULT NULL
)
RETURNS integer
LANGUAGE plpgsql AS $$
DECLARE
    v_updated integer;
BEGIN
    IF p_status NOT IN ('SUCCEEDED', 'FAILED', 'CANCELLED') THEN
        RAISE EXCEPTION 'complete_execution_node expects a terminal status, got %', p_status;
    END IF;

    IF p_status = 'FAILED' AND p_failure_reason IS NULL THEN
        RAISE EXCEPTION 'failure_reason is required when marking a node FAILED';
    END IF;

    UPDATE execution_nodes
    SET status         = p_status,
        failure_reason = CASE WHEN p_status = 'FAILED' THEN p_failure_reason ELSE failure_reason END,
        completed_at   = now(),
        updated_at     = now()
    WHERE organization_id      = p_organization_id
      AND workflow_instance_id = p_workflow_instance_id
      AND ref_id               = p_ref_id
      AND ref_type             = p_ref_type
      AND status IN ('PENDING', 'RUNNING');   -- never re-complete a terminal node

    GET DIAGNOSTICS v_updated = ROW_COUNT;
    RETURN v_updated;
END;
$$;


