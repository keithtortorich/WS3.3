-- Enum labels are the Python member NAMES, uppercase — not the .value
-- strings. SQLAlchemy's Enum() persists .name unless values_callable is
-- passed, and nothing in backend/app/ passes it. Confirmed against
-- 92ba5d1cd517_initial_schema.py, where every existing enum
-- (post_status, campaign_status, approval_status, ...) is uppercase.
CREATE TYPE workflow_node_type AS ENUM (
    'INTAKE', 'CAMPAIGN', 'POST', 'PUBLISH_JOB', 'APPROVAL', 'INTEGRATION_EVENT'
);

CREATE TYPE workflow_node_status AS ENUM (
    'PENDING', 'RUNNING', 'SUCCEEDED', 'FAILED', 'CANCELLED'
);

CREATE TYPE execution_node_ref_type AS ENUM (
    'CAMPAIGN', 'POST', 'SCHEDULE', 'PUBLISH_JOB', 'APPROVAL', 'AUDIT_LOG'
);

CREATE TABLE execution_nodes (
    -- No gen_random_uuid() server default: UUIDPkMixin generates ids
    -- application-side on purpose, so the same model runs on the SQLite
    -- test suite. See the design note at the top of app/models/base.py.
    id                   uuid         NOT NULL,
    organization_id      uuid         NOT NULL,
    workflow_instance_id uuid         NOT NULL,
    parent_node_id       uuid         NULL,
    node_type            workflow_node_type   NOT NULL,
    status               workflow_node_status NOT NULL,
    display_name         varchar(255) NULL,
    ref_id               uuid         NULL,
    ref_type             execution_node_ref_type NULL,
    failure_reason       varchar(1000) NULL,
    completed_at         timestamptz  NULL,
    -- TimestampMixin: both columns are NOT NULL with no server default, so
    -- every raw-SQL INSERT must supply them explicitly.
    created_at           timestamptz  NOT NULL,
    updated_at           timestamptz  NOT NULL,

    CONSTRAINT pk_execution_nodes PRIMARY KEY (id),
    CONSTRAINT fk_execution_nodes_organization_id
        FOREIGN KEY (organization_id) REFERENCES organizations (id) ON DELETE CASCADE,
    CONSTRAINT fk_execution_nodes_parent_node_id
        FOREIGN KEY (parent_node_id) REFERENCES execution_nodes (id) ON DELETE SET NULL
);

-- These five mirror index=True on the model; the names are what SQLAlchemy's
-- default naming convention produces, so autogenerate will match them.
CREATE INDEX ix_execution_nodes_organization_id      ON execution_nodes (organization_id);
CREATE INDEX ix_execution_nodes_workflow_instance_id ON execution_nodes (workflow_instance_id);
CREATE INDEX ix_execution_nodes_parent_node_id       ON execution_nodes (parent_node_id);
CREATE INDEX ix_execution_nodes_node_type            ON execution_nodes (node_type);
CREATE INDEX ix_execution_nodes_status               ON execution_nodes (status);
CREATE INDEX ix_execution_nodes_ref_id               ON execution_nodes (ref_id);
CREATE INDEX ix_execution_nodes_ref_type             ON execution_nodes (ref_type);

-- Hot-path composites. Not emitted by autogenerate — add them to the
-- migration by hand, after the autogenerated block.
--
-- Resolving (workflow_instance_id, ref_id, ref_type) -> node is the lookup
-- every status-completion write does; org first keeps it tenant-scoped.
CREATE INDEX ix_execution_nodes_org_workflow_ref
    ON execution_nodes (organization_id, workflow_instance_id, ref_type, ref_id);

-- Backs the "what is still in flight" operational query in section 4a.
CREATE INDEX ix_execution_nodes_org_open
    ON execution_nodes (organization_id, created_at DESC)
    WHERE status IN ('PENDING', 'RUNNING');


