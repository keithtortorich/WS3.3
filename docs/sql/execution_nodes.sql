-- 3b. One row per workflow instance: rollup status + counts.
CREATE OR REPLACE VIEW smm.workflow_instance_summary AS
SELECT
    n.organization_id,
    n.workflow_instance_id,
    max(n.display_name) FILTER (WHERE n.parent_node_id IS NULL) AS root_name,
    max(n.ref_id::text) FILTER (WHERE n.parent_node_id IS NULL) AS root_ref_id,
    count(*)                                                    AS node_count,
    count(*) FILTER (WHERE n.status = 'PENDING')                AS pending_count,
    count(*) FILTER (WHERE n.status = 'RUNNING')                AS running_count,
    count(*) FILTER (WHERE n.status = 'SUCCEEDED')              AS succeeded_count,
    count(*) FILTER (WHERE n.status = 'FAILED')                 AS failed_count,
    count(*) FILTER (WHERE n.status = 'CANCELLED')              AS cancelled_count,
    CASE
        WHEN count(*) FILTER (WHERE n.status = 'FAILED')  > 0 THEN 'FAILED'
        WHEN count(*) FILTER (WHERE n.status = 'RUNNING') > 0 THEN 'RUNNING'
        WHEN count(*) FILTER (WHERE n.status IN ('PENDING', 'RUNNING')) = 0 THEN 'SUCCEEDED'
        ELSE 'PENDING'
    END                                                         AS rollup_status,
    min(n.created_at)                                           AS started_at,
    max(n.completed_at) FILTER (
        WHERE n.status IN ('SUCCEEDED', 'FAILED', 'CANCELLED')
    )                                                           AS last_completed_at
FROM execution_nodes n
GROUP BY n.organization_id, n.workflow_instance_id;


-- ============================================================
-- 4. Operational queries
-- ============================================================

-- 4a. In-flight work for one tenant, oldest first — the recovery query.
-- "No in-memory session state" means a cold start must be able to rebuild
-- what is outstanding from this alone. Uses ix_execution_nodes_org_open.
SELECT
    n.workflow_instance_id,
    n.id AS node_id,
    n.node_type,
    n.status,
    n.display_name,
    n.ref_type,
    n.ref_id,
    n.created_at,
    now() - n.created_at AS age
FROM execution_nodes n
WHERE n.organization_id = :organization_id
  AND n.status IN ('PENDING', 'RUNNING')
ORDER BY n.created_at
LIMIT 500;


-- 4b. Stuck nodes — in flight past their SLA. Feed this to alerting.
SELECT
    n.organization_id,
    n.workflow_instance_id,
    n.id AS node_id,
    n.node_type,
    n.status,
    n.created_at,
    now() - n.created_at AS stuck_for
FROM execution_nodes n
WHERE n.status IN ('PENDING', 'RUNNING')
  AND n.created_at < now() - (:stuck_after_minutes || ' minutes')::interval
ORDER BY n.created_at;


-- 4c. Graph node joined to the domain row it references, for one campaign.
-- Replaces a 6-way LEFT JOIN: only one branch of the CASE is ever non-null
-- per row, so resolving the label per ref_type keeps the plan flat.
SELECT
    n.workflow_instance_id,
    n.node_type,
    n.status,
    n.ref_type,
    n.ref_id,
    CASE n.ref_type
        WHEN 'CAMPAIGN'    THEN (SELECT c.name        FROM campaigns    c WHERE c.id = n.ref_id AND c.organization_id = n.organization_id)
        WHEN 'POST'        THEN (SELECT left(p.caption, 80) FROM posts  p WHERE p.id = n.ref_id AND p.organization_id = n.organization_id)
        WHEN 'APPROVAL'    THEN (SELECT a.stage::text  FROM approvals   a WHERE a.id = n.ref_id AND a.organization_id = n.organization_id)
        WHEN 'PUBLISH_JOB' THEN (SELECT j.status::text FROM publish_jobs j WHERE j.id = n.ref_id AND j.organization_id = n.organization_id)
        ELSE NULL
    END AS ref_label,
    n.failure_reason,
    n.created_at,
    n.completed_at
FROM execution_nodes n
WHERE n.organization_id      = :organization_id
  AND n.workflow_instance_id = :workflow_instance_id
ORDER BY n.created_at;


-- 4d. Orphan check — posts with no execution node. Should return zero rows
-- once workflow creation is wired into the campaign/post creation flow;
-- non-zero means the bridge created domain rows without a graph.
SELECT p.id AS post_id, p.campaign_id, p.status, p.created_at
FROM posts p
WHERE p.organization_id = :organization_id
  AND NOT EXISTS (
      SELECT 1 FROM execution_nodes n
      WHERE n.organization_id = p.organization_id
        AND n.ref_type        = 'POST'
        AND n.ref_id          = p.id
  )
ORDER BY p.created_at DESC;


-- ============================================================
-- DRIFT FROM smm_gtm_bridge.sql SECTION 3
-- ============================================================
-- Each of these makes the older DDL/statements fail or misbehave against
-- the ExecutionNode model as written:
--
-- 1. Enum labels. Old file uses lowercase text ('pending', 'campaign') with
--    CHECK constraints. The model declares native PG enums, and SQLAlchemy
--    persists member NAMES, so the real labels are uppercase. This also
--    breaks an existing index in that file's section 5:
--        ix_publish_jobs_status_next ... WHERE status IN ('queued','retrying')
--    publish_job_status has labels QUEUED/RETRYING, so that predicate matches
--    nothing and the partial index is dead. Worth fixing there too.
--
-- 2. Missing updated_at. TimestampMixin makes it NOT NULL with no server
--    default. Every INSERT in the old section 3 omits it -> not-null violation.
--
-- 3. gen_random_uuid() as the id default. base.py states the server-side
--    default is deliberately not used, for SQLite parity. Keeping the old
--    default would let raw SQL insert rows the ORM path cannot reproduce.
--
-- 4. Missing display_name. Present on the model and populated by
--    WorkflowService.create_workflow_instance; absent from the old DDL.
--
-- 5. No FK on parent_node_id. The model declares
--    ForeignKey("execution_nodes.id", ondelete="SET NULL").
--
-- 6. Duplicate org index. Old file adds ix_execution_nodes_org while
--    OrgScopedMixin's index=True already yields
--    ix_execution_nodes_organization_id.
--
-- 7. No tenant predicate on the completion UPDATEs (old 3c), and no
--    idempotence guard on the child INSERTs (old 3b).
