-- 2a. Bootstrap a workflow instance and return its root node id.
--
-- Signature change from smm_gtm_bridge.sql 3a: that version returned the
-- generated workflow_instance_id and discarded the root node's id, so a
-- caller had no handle to pass as parent_node_id when appending children.
-- This returns both. It also takes workflow_instance_id as an argument
-- rather than generating it, matching WorkflowService.create_workflow_instance,
-- which requires the caller to supply it.
CREATE OR REPLACE FUNCTION smm.create_workflow_instance(
    p_organization_id      uuid,
    p_workflow_instance_id uuid,
    p_root_ref_id          uuid,
    p_root_ref_type        execution_node_ref_type,
    p_node_type            workflow_node_type DEFAULT 'CAMPAIGN',
    p_display_name         varchar(255) DEFAULT NULL
)
RETURNS TABLE (root_node_id uuid, workflow_instance_id uuid)
LANGUAGE plpgsql AS $$
DECLARE
    v_root_id uuid := gen_random_uuid();
    v_now     timestamptz := now();
BEGIN
    INSERT INTO execution_nodes (
        id, organization_id, workflow_instance_id, parent_node_id,
        node_type, status, display_name, ref_id, ref_type,
        created_at, updated_at
    )
    VALUES (
        v_root_id, p_organization_id, p_workflow_instance_id, NULL,
        p_node_type, 'SUCCEEDED',
        COALESCE(p_display_name, 'workflow-' || left(replace(p_workflow_instance_id::text, '-', ''), 8)),
        p_root_ref_id, p_root_ref_type,
        v_now, v_now
    );

    RETURN QUERY SELECT v_root_id, p_workflow_instance_id;
END;
$$;

