-- 3a. Flattened graph with depth, for rendering a workflow as a tree.
-- Recursive CTE walks down from the roots (parent_node_id IS NULL).
CREATE OR REPLACE VIEW smm.execution_graph AS
WITH RECURSIVE tree AS (
    SELECT
        n.id,
        n.organization_id,
        n.workflow_instance_id,
        n.parent_node_id,
        n.node_type,
        n.status,
        n.display_name,
        n.ref_id,
        n.ref_type,
        n.failure_reason,
        n.created_at,
        n.completed_at,
        0                       AS depth,
        ARRAY[n.created_at]     AS sort_path
    FROM execution_nodes n
    WHERE n.parent_node_id IS NULL

    UNION ALL

    SELECT
        c.id,
        c.organization_id,
        c.workflow_instance_id,
        c.parent_node_id,
        c.node_type,
        c.status,
        c.display_name,
        c.ref_id,
        c.ref_type,
        c.failure_reason,
        c.created_at,
        c.completed_at,
        t.depth + 1,
        t.sort_path || c.created_at
    FROM execution_nodes c
    JOIN tree t
      ON c.parent_node_id  = t.id
     -- A child must never cross tenants or workflows, even if a bad write
     -- created one; joining on all three keeps the view from leaking it.
     AND c.organization_id = t.organization_id
     AND c.workflow_instance_id = t.workflow_instance_id
)
SELECT * FROM tree;

